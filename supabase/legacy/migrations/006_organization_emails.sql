-- Migration 006: Organization Email Addresses Management
-- Table for storing official email addresses linked to organizations

CREATE TABLE IF NOT EXISTS organization_emails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT REFERENCES organizations(id) ON DELETE CASCADE NOT NULL,
  email TEXT NOT NULL,
  label TEXT DEFAULT 'Umumiy murojaatlar',
  is_primary BOOLEAN DEFAULT FALSE NOT NULL,
  is_verified BOOLEAN DEFAULT TRUE NOT NULL,
  sort_order INT DEFAULT 0 NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  CONSTRAINT unique_org_email UNIQUE (organization_id, email)
);

-- INDEXES
CREATE INDEX IF NOT EXISTS idx_org_emails_org_id ON organization_emails(organization_id);

