-- 1. EXTEND ORGANIZATIONS TABLE FOR BRANCHES, WORKING HOURS & LOCATION COORDINATES
ALTER TABLE organizations 
  ADD COLUMN IF NOT EXISTS parent_id BIGINT REFERENCES organizations(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS is_branch BOOLEAN DEFAULT FALSE NOT NULL,
  ADD COLUMN IF NOT EXISTS branch_type TEXT DEFAULT 'main' CHECK (branch_type IN ('main', 'branch', 'regional_office', 'district_office')),
  ADD COLUMN IF NOT EXISTS working_schedule JSONB DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS is_24_7 BOOLEAN DEFAULT FALSE NOT NULL,
  ADD COLUMN IF NOT EXISTS latitude NUMERIC(10, 7) DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS longitude NUMERIC(10, 7) DEFAULT NULL;

-- Create index for parent-child relationship lookups
CREATE INDEX IF NOT EXISTS idx_organizations_parent_id ON organizations(parent_id);

-- 2. CREATE ORGANIZATION ALIASES TABLE (FOR SEARCH SYNONYMS & ABBREVIATIONS)
CREATE TABLE IF NOT EXISTS organization_aliases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  alias TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  CONSTRAINT unique_org_alias UNIQUE (organization_id, alias)
);

CREATE INDEX IF NOT EXISTS idx_org_aliases_org_id ON organization_aliases(organization_id);
CREATE INDEX IF NOT EXISTS idx_org_aliases_text ON organization_aliases(alias);

-- 3. CREATE ORGANIZATION SERVICE KEYWORDS TABLE
CREATE TABLE IF NOT EXISTS organization_service_keywords (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  service_title TEXT NOT NULL,
  keywords TEXT[] DEFAULT '{}'::TEXT[] NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_org_service_keywords_org_id ON organization_service_keywords(organization_id);

-- 4. CREATE SEARCH QUERY ANALYTICS TABLE
CREATE TABLE IF NOT EXISTS search_query_analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  query_text TEXT NOT NULL,
  has_results BOOLEAN NOT NULL,
  result_count INT DEFAULT 0 NOT NULL,
  visitor_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_search_analytics_created ON search_query_analytics(created_at);
CREATE INDEX IF NOT EXISTS idx_search_analytics_query ON search_query_analytics(query_text);
CREATE INDEX IF NOT EXISTS idx_search_analytics_results ON search_query_analytics(has_results, created_at);

