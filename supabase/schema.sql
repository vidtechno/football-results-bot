-- Supabase Schema for Football Results Uzbek Website

-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. COMPETITIONS
CREATE TABLE IF NOT EXISTS competitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_competition_id INT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  country TEXT,
  logo_url TEXT,
  slug TEXT UNIQUE NOT NULL,
  code TEXT,
  is_featured BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 2. TEAMS
CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_team_id INT UNIQUE NOT NULL,
  competition_id BIGINT REFERENCES competitions(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  code TEXT,
  logo_url TEXT,
  country TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 3. FIXTURES
CREATE TABLE IF NOT EXISTS fixtures (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_fixture_id INT UNIQUE NOT NULL,
  competition_id BIGINT NOT NULL REFERENCES competitions(id) ON DELETE CASCADE,
  home_team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  away_team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  scheduled_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'NS',
  home_score INT,
  away_score INT,
  venue_name TEXT,
  round TEXT,
  raw_payload JSONB,
  synced_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 4. API SYNC STATE
CREATE TABLE IF NOT EXISTS api_sync_state (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint TEXT NOT NULL,
  status TEXT NOT NULL, -- 'SUCCESS' | 'ERROR'
  last_synced_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  records_synced INT DEFAULT 0,
  error_message TEXT,
  details JSONB
);

-- INDEXES for fast querying
CREATE INDEX IF NOT EXISTS idx_fixtures_scheduled_at ON fixtures(scheduled_at);
CREATE INDEX IF NOT EXISTS idx_fixtures_competition_id ON fixtures(competition_id);
CREATE INDEX IF NOT EXISTS idx_fixtures_status ON fixtures(status);
CREATE INDEX IF NOT EXISTS idx_teams_provider_team_id ON teams(provider_team_id);
CREATE INDEX IF NOT EXISTS idx_competitions_slug ON competitions(slug);

-- Enable Row Level Security (RLS) and allow public read access
ALTER TABLE competitions ENABLE ROW LEVEL SECURITY;
ALTER TABLE teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE fixtures ENABLE ROW LEVEL SECURITY;
ALTER TABLE api_sync_state ENABLE ROW LEVEL SECURITY;

-- Public read policies
CREATE POLICY "Allow public read on competitions" ON competitions FOR SELECT USING (true);
CREATE POLICY "Allow public read on teams" ON teams FOR SELECT USING (true);
CREATE POLICY "Allow public read on fixtures" ON fixtures FOR SELECT USING (true);
CREATE POLICY "Allow public read on api_sync_state" ON api_sync_state FOR SELECT USING (true);

-- Service role full access policies
CREATE POLICY "Allow service role full access on competitions" ON competitions FOR ALL USING (auth.role() = 'service_role');
CREATE POLICY "Allow service role full access on teams" ON teams FOR ALL USING (auth.role() = 'service_role');
CREATE POLICY "Allow service role full access on fixtures" ON fixtures FOR ALL USING (auth.role() = 'service_role');
CREATE POLICY "Allow service role full access on api_sync_state" ON api_sync_state FOR ALL USING (auth.role() = 'service_role');
